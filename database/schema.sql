-- DreamPlanner | PostgreSQL 15+ | referencyjny schemat MVP
-- Struktura referencyjna: backend wdraża ją przez migracje Alembic.
-- Wszystkie godziny pracy i dyspozycyjności są lokalnymi godzinami organizacji.
BEGIN;

CREATE TABLE roles (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE CHECK (code IN ('admin','manager','employee')),
    name VARCHAR(80) NOT NULL
);
INSERT INTO roles (code, name) VALUES
('admin','Administrator'), ('manager','Menadżer'), ('employee','Pracownik');

CREATE TABLE users (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    role_id SMALLINT NOT NULL REFERENCES roles(id),
    email VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    password_hash TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT users_email_not_blank CHECK (length(btrim(email)) > 0)
);
CREATE UNIQUE INDEX ux_users_email_lower ON users (lower(email));

CREATE TABLE positions (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT positions_name_not_blank CHECK (length(btrim(name)) > 0)
);

CREATE TABLE schedules (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    year INTEGER NOT NULL CHECK (year BETWEEN 2000 AND 2100),
    month INTEGER NOT NULL CHECK (month BETWEEN 1 AND 12),
    status VARCHAR(30) NOT NULL DEFAULT 'draft'
      CHECK (status IN ('draft','collecting','collection_closed','closed','published')),
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    collection_opened_at TIMESTAMPTZ,
    collection_closed_at TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    CONSTRAINT uq_schedules_period UNIQUE (year, month)
);

CREATE TABLE shift_requirements (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    schedule_id BIGINT NOT NULL REFERENCES schedules(id) ON DELETE CASCADE,
    position_id BIGINT NOT NULL REFERENCES positions(id),
    work_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    required_workers INTEGER NOT NULL CHECK (required_workers > 0),
    note TEXT,
    CONSTRAINT chk_shift_same_day CHECK (start_time < end_time),
    CONSTRAINT uq_shift_requirement UNIQUE (schedule_id, position_id, work_date, start_time, end_time)
);
CREATE INDEX ix_shift_requirements_schedule_date ON shift_requirements(schedule_id, work_date);

CREATE TABLE availability_submissions (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    schedule_id BIGINT NOT NULL REFERENCES schedules(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id),
    submitted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_availability_submission UNIQUE (schedule_id, user_id)
);
CREATE INDEX ix_availability_submissions_user ON availability_submissions(user_id);

CREATE TABLE availability_entries (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL REFERENCES availability_submissions(id) ON DELETE CASCADE,
    work_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    status VARCHAR(15) NOT NULL CHECK (status IN ('available','unavailable')),
    note TEXT,
    CONSTRAINT chk_availability_same_day CHECK (start_time < end_time),
    CONSTRAINT uq_availability_entry UNIQUE (submission_id, work_date, start_time, end_time)
);
CREATE INDEX ix_availability_entries_submission_date ON availability_entries(submission_id,work_date);

CREATE TABLE shift_assignments (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    shift_requirement_id BIGINT NOT NULL REFERENCES shift_requirements(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id),
    assigned_by BIGINT NOT NULL REFERENCES users(id),
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Potwierdzenie wymagane przez API przy statusie unavailable lub unknown.
    warning_type VARCHAR(20) CHECK (warning_type IN ('unavailable','unknown')),
    warning_acknowledged_at TIMESTAMPTZ,
    CONSTRAINT uq_shift_assignment UNIQUE (shift_requirement_id,user_id),
    CONSTRAINT chk_warning_ack_pair CHECK (
       (warning_type IS NULL AND warning_acknowledged_at IS NULL) OR
       (warning_type IS NOT NULL AND warning_acknowledged_at IS NOT NULL)
    )
);
CREATE INDEX ix_shift_assignments_user ON shift_assignments(user_id);

-- Spójność miesiąca: deklaracje i zmiany muszą dotyczyć miesiąca grafiku.
CREATE FUNCTION validate_schedule_dates() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE sy INTEGER; sm INTEGER; sid BIGINT;
BEGIN
  IF TG_TABLE_NAME = 'shift_requirements' THEN
    sid := NEW.schedule_id;
  ELSE
    SELECT schedule_id INTO sid FROM availability_submissions WHERE id = NEW.submission_id;
  END IF;
  SELECT year, month INTO sy, sm FROM schedules WHERE id = sid;
  IF sy IS NULL OR EXTRACT(YEAR FROM NEW.work_date)::int <> sy
     OR EXTRACT(MONTH FROM NEW.work_date)::int <> sm THEN
    RAISE EXCEPTION 'Data % musi nalezec do miesiaca grafiku %-%', NEW.work_date, sy, sm;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_shift_period BEFORE INSERT OR UPDATE OF schedule_id,work_date
ON shift_requirements FOR EACH ROW EXECUTE FUNCTION validate_schedule_dates();
CREATE TRIGGER trg_availability_period BEFORE INSERT OR UPDATE OF submission_id,work_date
ON availability_entries FOR EACH ROW EXECUTE FUNCTION validate_schedule_dates();

-- Brak nachodzących na siebie deklaracji jednego pracownika w obrębie zgłoszenia.
CREATE FUNCTION prevent_overlapping_availability() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF EXISTS (
  SELECT 1 FROM availability_entries e
  WHERE e.submission_id=NEW.submission_id AND e.work_date=NEW.work_date
    AND e.id<>COALESCE(NEW.id,-1)
    AND NEW.start_time < e.end_time AND e.start_time < NEW.end_time
 ) THEN
  RAISE EXCEPTION 'Nakladajace sie przedzialy dyspozycyjnosci';
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER trg_availability_overlap BEFORE INSERT OR UPDATE
ON availability_entries FOR EACH ROW EXECUTE FUNCTION prevent_overlapping_availability();

-- Przydział nie może kolidować czasowo z innym przydziałem tego pracownika.
CREATE FUNCTION validate_shift_assignment() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE s shift_requirements%ROWTYPE;
BEGIN
 SELECT * INTO s FROM shift_requirements WHERE id=NEW.shift_requirement_id;
 IF EXISTS (
    SELECT 1 FROM shift_assignments a
    JOIN shift_requirements other_s ON other_s.id=a.shift_requirement_id
    WHERE a.user_id=NEW.user_id AND a.id<>COALESCE(NEW.id,-1)
      AND other_s.work_date=s.work_date
      AND s.start_time < other_s.end_time AND other_s.start_time < s.end_time
 ) THEN RAISE EXCEPTION 'Pracownik ma kolidujacy przydzial'; END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER trg_assignment_overlap BEFORE INSERT OR UPDATE OF shift_requirement_id,user_id
ON shift_assignments FOR EACH ROW EXECUTE FUNCTION validate_shift_assignment();

COMMIT;
